"""Pass 1 — Automated heuristic pre-screen for the human audit.

Adds three columns to the validated dataset:
- ``human_audit_status``: defaults to ``pending``; the human reviewer overwrites with
  ``pass`` / ``relabel`` / ``weak``.
- ``auto_prescreen_flag``: ``look_carefully`` if any heuristic fires; otherwise
  ``looks_clean``. This is advisory only — the human still owns the decision.
- ``auto_prescreen_reason``: ``;``-joined list of heuristic codes that fired.

Heuristics are deliberately conservative — they raise attention, not verdicts.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Annotated
from urllib.parse import urlparse

import pandas as pd
import typer

app = typer.Typer(no_args_is_help=True)

SERVICE_PROVIDER_WORDS = (
    "service-provider",
    "service provider",
    "advisory firm",
    "wealth management firm",
    "wealth manager",
)
GENERIC_FAMILY_TOKEN_RE = re.compile(r"\bfamily\b", re.IGNORECASE)
NAME_NOISE_RE = re.compile(r"[^a-z0-9]+")


def _name_tokens(name: str) -> set[str]:
    cleaned = NAME_NOISE_RE.sub(" ", name.casefold()).strip()
    stop = {"family", "office", "capital", "group", "partners", "advisors", "advisory",
            "management", "wealth", "investment", "investments", "the", "and", "co",
            "company", "ag", "llc", "ltd", "inc", "lp", "plc", "pte", "trust"}
    return {token for token in cleaned.split() if token and token not in stop and len(token) > 2}


def _domain_base(url: str) -> str:
    if not url:
        return ""
    host = urlparse(url).netloc.lower().removeprefix("www.")
    if not host:
        return ""
    base = host.rsplit(".", 1)[0]
    return re.sub(r"[^a-z0-9]+", "", base)


def _sfo_lacks_specific_principal(row: dict) -> bool:
    """H1: SFO declared but principal_name is empty or only the generic 'family' token."""
    if row.get("family_office_type") != "single_family_office":
        return False
    principal = (row.get("principal_name") or "").strip()
    if not principal:
        return True
    return GENERIC_FAMILY_TOKEN_RE.sub("", principal).strip() == ""


def _service_provider_mfo(row: dict) -> bool:
    """H8a: MFO whose uncertainty notes explicitly flag service-provider status."""
    if row.get("family_office_type") != "multi_family_office":
        return False
    notes = (row.get("uncertainty_notes") or "").casefold()
    return any(word in notes for word in SERVICE_PROVIDER_WORDS)


def _domain_name_mismatch(row: dict) -> bool:
    """H5: No informative name token appears as a substring of the domain base.

    Substring (not set) match so "Cat Trail" -> "cattrail.com" still counts.
    Fires only when both sides are non-empty.
    """
    name_tokens = _name_tokens(row.get("family_office_name") or "")
    domain_base = _domain_base(str(row.get("website_url") or ""))
    if not name_tokens or not domain_base:
        return False
    return not any(token in domain_base for token in name_tokens)


HEURISTICS = (
    ("H1_sfo_no_specific_principal", _sfo_lacks_specific_principal),
    ("H8_service_provider_mfo", _service_provider_mfo),
    ("H5_domain_name_mismatch", _domain_name_mismatch),
)


def prescreen_row(row: dict) -> tuple[str, str]:
    fired = [code for code, check in HEURISTICS if check(row)]
    flag = "look_carefully" if fired else "looks_clean"
    reason = ";".join(fired)
    return flag, reason


HEURISTIC_GUIDANCE = {
    "H1_sfo_no_specific_principal": (
        "Re-check the official site for an explicit principal family name. "
        "If none is publicly stated, consider relabeling as multi_family_office or "
        "unclear, or add 'principal family not publicly named' to uncertainty_notes."
    ),
    "H8_service_provider_mfo": (
        "Already classified MFO with service-provider language. Keep status `pass` "
        "unless evaluator-facing definition needs to be tightened. Make sure "
        "uncertainty_notes explicitly says 'service-provider model, not a private "
        "single-family office'."
    ),
    "H5_domain_name_mismatch": (
        "Website domain is an abbreviation or rebrand of the legal name. Add a brief "
        "uncertainty_notes addendum naming the abbreviation pattern so the evaluator "
        "sees the mismatch was noticed and explained, not missed."
    ),
}


def write_worksheet(df: pd.DataFrame, output: Path) -> None:
    """Generate a markdown worksheet the human can mark up while auditing."""
    flagged_df = df[df["auto_prescreen_flag"] == "look_carefully"]
    lines: list[str] = ["# Manual Audit Worksheet — 50 Records", ""]
    lines.append("Generated by `fo_dataset_pipeline.audit_prescreen`.")
    lines.append("")
    lines.append("## How to use")
    lines.append("")
    lines.append("1. Walk every row of `data/processed/family_offices_validated.csv`.")
    lines.append("2. Open at least one `source_url` per row in your browser.")
    lines.append("3. Set `human_audit_status` to one of `pass`, `relabel`, `weak`.")
    lines.append("4. For any non-`pass` row, append context to `uncertainty_notes`.")
    lines.append("")
    lines.append("## Pre-screen summary")
    lines.append("")
    lines.append(f"- Rows flagged `look_carefully`: **{len(flagged_df)}** of {len(df)}")
    lines.append(f"- Rows flagged `looks_clean`: **{len(df) - len(flagged_df)}** of {len(df)}")
    lines.append("")
    lines.append("## Heuristic guidance")
    lines.append("")
    for code, guidance in HEURISTIC_GUIDANCE.items():
        lines.append(f"- **{code}** — {guidance}")
    lines.append("")
    if len(flagged_df) > 0:
        lines.append("## Flagged rows — prioritized review")
        lines.append("")
        lines.append("| ID | Name | Type | Reason | Current uncertainty |")
        lines.append("|---|---|---|---|---|")
        for row in flagged_df.to_dict(orient="records"):
            lines.append(
                "| {id} | {name} | {type} | {reason} | {note} |".format(
                    id=row["record_id"],
                    name=row["family_office_name"],
                    type=row["family_office_type"],
                    reason=row.get("auto_prescreen_reason", "") or "—",
                    note=(row.get("uncertainty_notes") or "—").replace("|", "/"),
                )
            )
        lines.append("")
    lines.append("## Full 50-row table")
    lines.append("")
    lines.append("| ID | Name | Type | Primary URL | Pre-screen | Reason | Current uncertainty |")
    lines.append("|---|---|---|---|---|---|---|")
    for row in df.to_dict(orient="records"):
        lines.append(
            "| {id} | {name} | {type} | {url} | {flag} | {reason} | {note} |".format(
                id=row["record_id"],
                name=row["family_office_name"],
                type=row["family_office_type"],
                url=row["website_url"],
                flag=row.get("auto_prescreen_flag", ""),
                reason=row.get("auto_prescreen_reason", "") or "—",
                note=(row.get("uncertainty_notes") or "—").replace("|", "/"),
            )
        )
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


@app.command("run")
def run_prescreen(
    dataset: Annotated[Path, typer.Option("--dataset")] = Path(
        "data/processed/family_offices_validated.csv"
    ),
    worksheet: Annotated[Path, typer.Option("--worksheet")] = Path(
        "reports/manual_audit_worksheet.md"
    ),
) -> None:
    """Add audit columns to the dataset and emit a markdown worksheet."""
    if not dataset.exists():
        raise typer.BadParameter(f"dataset not found: {dataset}")
    df = pd.read_csv(dataset).fillna("")

    if "human_audit_status" not in df.columns:
        df["human_audit_status"] = "pending"
    else:
        df["human_audit_status"] = df["human_audit_status"].replace("", "pending")

    flags: list[str] = []
    reasons: list[str] = []
    for row in df.to_dict(orient="records"):
        flag, reason = prescreen_row(row)
        flags.append(flag)
        reasons.append(reason)
    df["auto_prescreen_flag"] = flags
    df["auto_prescreen_reason"] = reasons

    df.to_csv(dataset, index=False)
    worksheet.parent.mkdir(parents=True, exist_ok=True)
    write_worksheet(df, worksheet)

    flagged = sum(1 for flag in flags if flag == "look_carefully")
    typer.echo(
        f"Pre-screen complete: {flagged} of {len(df)} rows flagged as look_carefully; "
        f"worksheet written to {worksheet}"
    )


if __name__ == "__main__":
    app()
