from __future__ import annotations

from typing import Any


def _q(
    question_id: str,
    category: str,
    question: str,
    gold_record_ids: list[str],
    expected_behavior: str,
    *,
    must_include: list[str] | None = None,
    must_exclude: list[str] | None = None,
    expected_intent: str | None = None,
    failure_mode: str = "",
    notes: str = "",
) -> dict[str, Any]:
    row: dict[str, Any] = {
        "id": question_id,
        "category": category,
        "question": question,
        "gold_record_ids": gold_record_ids,
        "expected_behavior": expected_behavior,
        "must_include": must_include or [],
        "must_exclude": must_exclude or [],
    }
    if expected_intent:
        row["expected_intent"] = expected_intent
    if failure_mode:
        row["failure_mode"] = failure_mode
    if notes:
        row["notes"] = notes
    return row


